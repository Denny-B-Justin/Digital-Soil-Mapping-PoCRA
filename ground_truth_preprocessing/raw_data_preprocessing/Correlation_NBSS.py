def get_inference(x):
    abs_x = abs(x)
    if abs_x >= 0.7:
        return 'Very Strong'
    elif abs_x >= 0.5:
        return 'Strong'
    elif abs_x >= 0.25:
        return 'Good'
    elif abs_x >= 0.1:
        return 'Weak'
    else:
        return 'Very Weak'

corr_pairs['Inferance'] = corr_pairs['Correlation Value'].apply(get_inference)
corr_pairs['Correlation Value'] = corr_pairs['Correlation Value'].round(2)

