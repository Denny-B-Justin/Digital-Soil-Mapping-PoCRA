def highlight_row(row):
    corr = row['Correlation Value']
    if corr >= 0.25:
        return ['background-color: #b6ffb6'] * len(row)  # light green
    elif corr <= -0.25:
        return ['background-color: #ffcccc'] * len(row)  # light red
    else:
        return [''] * len(row)

